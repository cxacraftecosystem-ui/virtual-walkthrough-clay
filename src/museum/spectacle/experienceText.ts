const TABLES: Record<Lang, Partial<Record<XKey, string>>> = { en: EN, hi: HI, bn: BN }

export const isXKey = (k: string): k is XKey => k in EN

/** Keys a language does not translate yet (tests). */
export const untranslated = (lang: Lang): XKey[] => (Object.keys(EN) as XKey[]).filter((k) => !TABLES[lang][k])

/** An experience string in `lang` (English when a translation is missing). */
export function xtIn(lang: Lang, key: XKey, vars?: Vars): string {
  return format(TABLES[lang][key] ?? EN[key], vars)
}

/** An experience string in the current language. */
export const xt = (key: XKey, vars?: Vars) => xtIn(getLang(), key, vars)

export type XT = (key: XKey, vars?: Vars) => string

/** React: re-renders when the language changes. */
export function useXT(): XT {
  const lang = useLang()
  return (key, vars) => xtIn(lang, key, vars)
}
