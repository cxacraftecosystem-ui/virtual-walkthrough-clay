/** Localised tour caption field: stop.i18n → TOUR_TEXT → English. */
export function tourField(stop: { id: string; place: string; title: string; text: string; i18n?: Partial<Record<AltLang, Caption>> }, field: keyof Caption, lang: 'en' | AltLang): string {
  if (lang !== 'en') {
    const v = stop.i18n?.[lang]?.[field] ?? TOUR_TEXT[stop.id]?.[lang]?.[field]
    if (v && v.trim()) return v
  }
  return stop[field]
}

/** True when a caption in `lang` exists (so narration can use a matching voice). */
export function hasTourTranslation(stop: { id: string; i18n?: Partial<Record<AltLang, Caption>> }, lang: 'en' | AltLang) {
  return lang === 'en' || !!(stop.i18n?.[lang]?.text ?? TOUR_TEXT[stop.id]?.[lang]?.text)
}
